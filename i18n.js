/* ═══════════════════════════════════════════════════════════════════════════
   ZENOFIT — INTERFACE LANGUAGES
   English · Українська · Svenska

   Two dictionaries live here.

   1. UI[lang] — every line of interface text, keyed by a short dotted name.
      Placeholders are {braced} and filled by T("key", {name: value}).

   2. EX[lang] — the built-in exercise library, as an array running in the
      SAME ORDER as DEFAULT_LIBRARY in app.js, one entry per exercise:
      [name, equipment, alternatives, note]. English isn't repeated here;
      it's read straight off DEFAULT_LIBRARY.

   ── The one rule ──────────────────────────────────────────────────────
   Translations are a DISPLAY layer and nothing else. Everything the app
   stores — an entry's exercise name, a group's name, a goal's key — stays
   in the English form it was written in, because those strings are the
   identity of the record. Switching to Svenska must never make a logged
   workout point at an exercise that no longer exists. So:

     · built-in exercises are translated by their stable "default-N" id
     · built-in groups carry a `key` and are translated by that
     · anything the user typed themselves is shown exactly as they typed it

   Adding a language: add it to LANGS, add a UI[code] block, add an EX[code]
   array of 41 rows. Any key you leave out quietly falls back to English, so
   a partial translation is always safe to ship.
   ═══════════════════════════════════════════════════════════════════════════ */

"use strict";

const LANGS = [
  { code: "en", label: "English", short: "EN" },
  { code: "uk", label: "Українська", short: "UA" },
  { code: "sv", label: "Svenska", short: "SV" },
];

/* The BCP-47 tag handed to toLocaleDateString, so month and weekday names
   in the calendar follow the chosen language rather than the device. */
const LOCALES = { en: "en-GB", uk: "uk-UA", sv: "sv-SE" };

/* A saved language the app no longer ships falls back to English rather
   than leaving every string to hunt for a dictionary that isn't there. */
const LANG_CODES = LANGS.map((l) => l.code);
const resolveLang = (code) => (LANG_CODES.includes(code) ? code : "en");

const UI = {};   // filled in below, one block per language
const EX = {};   // built-in exercise strings, parallel to DEFAULT_LIBRARY

/* Long-form copy carries its own emphasis so translators control it:
   *bold* and _italic_. A lone asterisk (the "required field" mark) needs a
   partner to become markup, so "Name *" is left alone. */
const emphasize = (s) => String(s)
  .replace(/\*([^*]+)\*/g, '<b style="color:var(--text)">$1</b>')
  .replace(/_([^_]+)_/g, "<i>$1</i>");

/* The one function the app calls. Missing keys fall back to English, then
   to the key itself, so a half-finished translation degrades quietly
   instead of blanking the screen. */
function T(key, vars) {
  const lang = resolveLang(typeof state !== "undefined" && state && state.settings && state.settings.lang);
  let s = (UI[lang] && UI[lang][key]);
  if (s == null) s = UI.en[key];
  if (s == null) return key;
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return emphasize(s);
}

/* Plural picking: English-style (one / other) for en+sv, Slavic
   (one / few / many) for uk. Call with the base key — TN("day", n)
   looks for "day.one" / "day.few" / "day.many" / "day.other". */
function TN(key, n) {
  const lang = resolveLang(typeof state !== "undefined" && state && state.settings && state.settings.lang);
  let form;
  if (lang === "uk") {
    const m10 = n % 10, m100 = n % 100;
    form = (m10 === 1 && m100 !== 11) ? "one"
      : (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) ? "few"
      : "many";
  } else {
    form = n === 1 ? "one" : "other";
  }
  let s = (UI[lang] && UI[lang][key + "." + form]);
  if (s == null) s = (UI[lang] && UI[lang][key + ".other"]) ?? (UI[lang] && UI[lang][key + ".many"]);
  if (s == null) s = UI.en[key + "." + (n === 1 ? "one" : "other")] ?? UI.en[key + ".other"];
  if (s == null) return key;
  return emphasize(String(s).split("{n}").join(n));
}

/* The locale used for month and weekday names on the calendar. */
